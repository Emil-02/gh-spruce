var tmpl = template.Must(template.New("card").Parse(svg))

func ringColor(score int) string {
	switch {
	case score >= 85:
		return "#2ea043"
	case score >= 55:
		return "#d29922"
	}
	return "#f85149"
}

func xmlEscape(s string) string {
	var b bytes.Buffer
	_ = xmlEscapeTo(&b, s)
	return b.String()
}

func xmlEscapeTo(b *bytes.Buffer, s string) error {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&#39;")
	_, err := b.WriteString(r.Replace(s))
	return err
}

// Render produces the SVG. Statistics only consider public repositories so
// the card never leaks information about private ones.
func Render(rep *checks.Report, themeName string) (string, error) {
	th, ok := Themes[themeName]
	if !ok {
		return "", fmt.Errorf("unknown theme %q (available: %s)", themeName, strings.Join(ThemeNames(), ", "))
	}
	type counter struct{ pass, total int }
	count := map[string]*counter{}
	public := 0
	for _, rr := range rep.Repos {
		if rr.Repo.Private {
			continue
		}
		public++
		for _, x := range rr.Results {
			if x.Status == checks.Skip {
				continue
			}
			c := count[x.ID]
			if c == nil {
				c = &counter{}
				count[x.ID] = c
			}
			c.total++
			if x.Status == checks.Pass {
				c.pass++
			}
		}
	}
	frac := func(id string) string {
		c := count[id]
		if c == nil || c.total == 0 {
			return "–"
		}
		return fmt.Sprintf("%d / %d", c.pass, c.total)
	}
	stats := []stat{
		{Label: "Public repositories", Value: fmt.Sprint(public)},
		{Label: "Licensed", Value: frac("license")},
		{Label: "With CI", Value: frac("ci")},
		{Label: "Tagged with topics", Value: frac("topics")},
		{Label: "Meaningful README", Value: frac("readme")},
	}
	for i := range stats {
		stats[i].Y = 70 + i*24
	}
	circ := 2 * math.Pi * 50
	d := data{
		Theme: th, Login: xmlEscape(rep.Profile.Login), Grade: rep.Grade, Score: rep.Score,
		Ring: ringColor(rep.Score), Circ: circ, Offset: circ * (1 - float64(rep.Score)/100),
		Stats: stats, Updated: rep.GeneratedAt.Format("2006-01-02"),
	}
	var b bytes.Buffer
	if err := tmpl.Execute(&b, d); err != nil {
		return "", err
	}
	return b.String(), nil
}
